#!/usr/bin/env python3
"""Regenerates internal/render/vulkan/shaders.go from the GLSL sources.

Requires glslangValidator on PATH (apt install glslang-tools) or set
GLSLANG to its path. Run from the repo root:

	python3 internal/render/vulkan/shaders/gen.py
"""
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'shaders.go')

SHADERS = [
    ('quad', 'vert', 'quadVertexShaderSpv',
     'quadVertexShaderSpv is the compiled SPIR-V bytecode for drawing solid color rectangles.'),
    ('quad', 'frag', 'quadFragmentShaderSpv',
     'quadFragmentShaderSpv is the compiled SPIR-V bytecode for solid color rectangles.'),
    ('texture', 'vert', 'texVertexShaderSpv',
     'texVertexShaderSpv is the compiled SPIR-V bytecode for drawing textured window tiles.'),
    ('texture', 'frag', 'texFragmentShaderSpv',
     'texFragmentShaderSpv is the compiled SPIR-V bytecode for sampling window textures.'),
]


def compile(name, kind):
    src = os.path.join(HERE, '%s.%s' % (name, kind))
    spv = src + '.spv'
    r = subprocess.run([GLSLANG, '-V', src, '-o', spv], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr)
        sys.exit(1)
    data = open(spv, 'rb').read()
    return struct.unpack('<%dI' % (len(data) // 4), data)


if __name__ == '__main__':
    GLSLANG = os.environ.get('GLSLANG', 'glslangValidator')
    parts = ['// Code generated by shaders/gen.py. DO NOT EDIT.', '', 'package vulkan', '']
    for base, kind, name, comment in SHADERS:
        words = list(compile(base, kind))
        emit = ['// ' + comment, 'var %s = []uint32{' % name]
        for i in range(0, len(words), 8):
            emit.append('\t' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
        emit.append('}')
        parts.append('\n'.join(emit))
    open(OUT, 'w').write('\n\n'.join(parts) + '\n')
    print('generated', OUT)
