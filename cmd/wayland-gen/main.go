package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"strings"
	"unicode"
)

type Protocol struct {
	XMLName    xml.Name    `xml:"protocol"`
	Name       string      `xml:"name,attr"`
	Interfaces []Interface `xml:"interface"`
}

type Interface struct {
	Name        string    `xml:"name,attr"`
	Version     int       `xml:"version,attr"`
	Description string    `xml:"description"`
	Requests    []Message `xml:"request"`
	Events      []Message `xml:"event"`
	Enums       []Enum    `xml:"enum"`
}

type Message struct {
	Name        string `xml:"name,attr"`
	Type        string `xml:"type,attr"`
	Since       int    `xml:"since,attr"`
	Description string `xml:"description"`
	Args        []Arg  `xml:"arg"`
}

type Arg struct {
	Name      string `xml:"name,attr"`
	Type      string `xml:"type,attr"` // int, uint, fixed, string, object, new_id, array, fd
	Interface string `xml:"interface,attr"`
	Summary   string `xml:"summary,attr"`
}

type Enum struct {
	Name    string      `xml:"name,attr"`
	Since   int         `xml:"since,attr"`
	Entries []EnumEntry `xml:"entry"`
}

type EnumEntry struct {
	Name    string `xml:"name,attr"`
	Value   string `xml:"value,attr"`
	Summary string `xml:"summary,attr"`
}

func toCamelCase(s string) string {
	parts := strings.Split(s, "_")
	for i := range parts {
		if len(parts[i]) > 0 {
			r := []rune(parts[i])
			r[0] = unicode.ToUpper(r[0])
			parts[i] = string(r)
		}
	}
	return strings.Join(parts, "")
}

func goType(arg Arg) string {
	switch arg.Type {
	case "int":
		return "int32"
	case "uint":
		return "uint32"
	case "fixed":
		return "wire.Fixed"
	case "string":
		return "string"
	case "object":
		return "uint32"
	case "new_id":
		return "uint32"
	case "array":
		return "[]byte"
	case "fd":
		return "int"
	default:
		return "uint32"
	}
}

func generateGo(p Protocol, pkgName string) ([]byte, error) {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "// Code generated by wayland-gen from %s. DO NOT EDIT.\n\n", p.Name)
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	fmt.Fprintf(&buf, "import (\n")
	fmt.Fprintf(&buf, "\t\"fmt\"\n")
	fmt.Fprintf(&buf, "\t\"bloxwm/internal/wire\"\n")
	fmt.Fprintf(&buf, ")\n\n")

	for _, iface := range p.Interfaces {
		ifaceGoName := toCamelCase(iface.Name)
		fmt.Fprintf(&buf, "// %s interface (version %d)\n", iface.Name, iface.Version)
		fmt.Fprintf(&buf, "const %sInterface = \"%s\"\n", ifaceGoName, iface.Name)
		fmt.Fprintf(&buf, "const %sVersion = %d\n\n", ifaceGoName, iface.Version)

		// Enums
		for _, enum := range iface.Enums {
			enumGoName := ifaceGoName + toCamelCase(enum.Name)
			fmt.Fprintf(&buf, "type %s uint32\n\nconst (\n", enumGoName)
			for _, entry := range enum.Entries {
				entryName := enumGoName + toCamelCase(entry.Name)
				fmt.Fprintf(&buf, "\t%s %s = %s\n", entryName, enumGoName, entry.Value)
			}
			fmt.Fprintf(&buf, ")\n\n")
		}

		// Request opcodes (client -> server)
		if len(iface.Requests) > 0 {
			fmt.Fprintf(&buf, "// Request opcodes for %s\nconst (\n", iface.Name)
			for idx, req := range iface.Requests {
				reqGoName := ifaceGoName + "Op" + toCamelCase(req.Name)
				fmt.Fprintf(&buf, "\t%s uint16 = %d\n", reqGoName, idx)
			}
			fmt.Fprintf(&buf, ")\n\n")
		}

		// Event opcodes (server -> client)
		if len(iface.Events) > 0 {
			fmt.Fprintf(&buf, "// Event opcodes for %s\nconst (\n", iface.Name)
			for idx, ev := range iface.Events {
				evGoName := ifaceGoName + "EventOp" + toCamelCase(ev.Name)
				fmt.Fprintf(&buf, "\t%s uint16 = %d\n", evGoName, idx)
			}
			fmt.Fprintf(&buf, ")\n\n")
		}

		// Server handler interface
		fmt.Fprintf(&buf, "// %sHandler represents the server-side request handler for %s.\n", ifaceGoName, iface.Name)
		fmt.Fprintf(&buf, "type %sHandler interface {\n", ifaceGoName)
		for _, req := range iface.Requests {
			methodName := "Handle" + toCamelCase(req.Name)
			var args []string
			args = append(args, "senderID uint32")
			for _, arg := range req.Args {
				if arg.Type == "new_id" && arg.Interface == "" {
					args = append(args, "ifaceName string", "version uint32", fmt.Sprintf("%s uint32", toCamelCase(arg.Name)))
				} else {
					args = append(args, fmt.Sprintf("%s %s", toCamelCase(arg.Name), goType(arg)))
				}
			}
			fmt.Fprintf(&buf, "\t%s(%s) error\n", methodName, strings.Join(args, ", "))
		}
		fmt.Fprintf(&buf, "}\n\n")

		// Dispatcher function
		fmt.Fprintf(&buf, "// Dispatch%s decodes incoming requests for %s and calls the handler.\n", ifaceGoName, iface.Name)
		fmt.Fprintf(&buf, "func Dispatch%s(r *wire.Reader, hdr wire.Header, h %sHandler) error {\n", ifaceGoName, ifaceGoName)
		fmt.Fprintf(&buf, "\tswitch hdr.Opcode {\n")
		for idx, req := range iface.Requests {
			fmt.Fprintf(&buf, "\tcase %d: // %s\n", idx, req.Name)
			var callArgs []string
			callArgs = append(callArgs, "hdr.ObjectID")
			for _, arg := range req.Args {
				argVar := "arg" + toCamelCase(arg.Name)
				switch arg.Type {
				case "uint", "object":
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadUint32()\n", argVar)
					callArgs = append(callArgs, argVar)
				case "int":
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadInt32()\n", argVar)
					callArgs = append(callArgs, argVar)
				case "fixed":
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadFixed()\n", argVar)
					callArgs = append(callArgs, argVar)
				case "string":
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadString()\n", argVar)
					callArgs = append(callArgs, argVar)
				case "array":
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadArray()\n", argVar)
					callArgs = append(callArgs, argVar)
				case "fd":
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadFD()\n", argVar)
					callArgs = append(callArgs, argVar)
				case "new_id":
					if arg.Interface == "" {
						fmt.Fprintf(&buf, "\t\t%sIface, err := r.ReadString()\n", argVar)
						fmt.Fprintf(&buf, "\t\tif err != nil { return fmt.Errorf(\"failed reading %s.%s.%s.iface: %%w\", err) }\n", iface.Name, req.Name, arg.Name)
						fmt.Fprintf(&buf, "\t\t%sVer, err := r.ReadUint32()\n", argVar)
						fmt.Fprintf(&buf, "\t\tif err != nil { return fmt.Errorf(\"failed reading %s.%s.%s.ver: %%w\", err) }\n", iface.Name, req.Name, arg.Name)
						callArgs = append(callArgs, argVar+"Iface", argVar+"Ver")
					}
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadUint32()\n", argVar)
					callArgs = append(callArgs, argVar)
				default:
					fmt.Fprintf(&buf, "\t\t%s, err := r.ReadUint32()\n", argVar)
					callArgs = append(callArgs, argVar)
				}
				fmt.Fprintf(&buf, "\t\tif err != nil {\n\t\t\treturn fmt.Errorf(\"failed reading %s.%s.%s: %%w\", err)\n\t\t}\n", iface.Name, req.Name, arg.Name)
			}
			fmt.Fprintf(&buf, "\t\treturn h.Handle%s(%s)\n", toCamelCase(req.Name), strings.Join(callArgs, ", "))
		}
		fmt.Fprintf(&buf, "\tdefault:\n")
		fmt.Fprintf(&buf, "\t\treturn fmt.Errorf(\"unknown opcode %%d for interface %s\", hdr.Opcode)\n", iface.Name)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "}\n\n")

		// Event senders (server -> client)
		for idx, ev := range iface.Events {
			evMethod := "Send" + ifaceGoName + toCamelCase(ev.Name)
			var params []string
			params = append(params, "w *wire.Writer", "targetID uint32")
			for _, arg := range ev.Args {
				params = append(params, fmt.Sprintf("%s %s", toCamelCase(arg.Name), goType(arg)))
			}
			fmt.Fprintf(&buf, "// %s writes a %s.%s event.\n", evMethod, iface.Name, ev.Name)
			fmt.Fprintf(&buf, "func %s(%s) error {\n", evMethod, strings.Join(params, ", "))
			fmt.Fprintf(&buf, "\tstart := w.BeginMessage(targetID, %d)\n", idx)
			for _, arg := range ev.Args {
				argVar := toCamelCase(arg.Name)
				switch arg.Type {
				case "uint", "object", "new_id":
					fmt.Fprintf(&buf, "\tif err := w.WriteUint32(%s); err != nil { return err }\n", argVar)
				case "int":
					fmt.Fprintf(&buf, "\tif err := w.WriteInt32(%s); err != nil { return err }\n", argVar)
				case "fixed":
					fmt.Fprintf(&buf, "\tif err := w.WriteFixed(%s); err != nil { return err }\n", argVar)
				case "string":
					fmt.Fprintf(&buf, "\tif err := w.WriteString(%s); err != nil { return err }\n", argVar)
				case "array":
					fmt.Fprintf(&buf, "\tif err := w.WriteArray(%s); err != nil { return err }\n", argVar)
				case "fd":
					fmt.Fprintf(&buf, "\tif err := w.WriteFD(%s); err != nil { return err }\n", argVar)
				default:
					fmt.Fprintf(&buf, "\tif err := w.WriteUint32(%s); err != nil { return err }\n", argVar)
				}
			}
			fmt.Fprintf(&buf, "\treturn w.EndMessage(start, targetID, %d)\n", idx)
			fmt.Fprintf(&buf, "}\n\n")
		}
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("gofmt error: %w\nGenerated code:\n%s", err, buf.String())
	}
	return formatted, nil
}

func main() {
	if len(os.Args) < 4 {
		fmt.Fprintf(os.Stderr, "Usage: %s <input.xml> <pkgName> <output.go>\n", os.Args[0])
		os.Exit(1)
	}

	xmlPath := os.Args[1]
	pkgName := os.Args[2]
	outputPath := os.Args[3]

	f, err := os.Open(xmlPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error opening %s: %v\n", xmlPath, err)
		os.Exit(1)
	}
	defer f.Close()

	data, err := io.ReadAll(f)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading %s: %v\n", xmlPath, err)
		os.Exit(1)
	}

	var p Protocol
	if err := xml.Unmarshal(data, &p); err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing XML %s: %v\n", xmlPath, err)
		os.Exit(1)
	}

	goSrc, err := generateGo(p, pkgName)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Code generation error: %v\n", err)
		os.Exit(1)
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "Error creating output dir: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(outputPath, goSrc, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", outputPath, err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated %s (%d bytes)\n", outputPath, len(goSrc))
}
